"""
FraudShield AI — Pydantic Request & Response Schemas
Handles input validation and API response shaping.
"""
from datetime import datetime
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, field_validator, ConfigDict
from enum import Enum


# ─── Enums ────────────────────────────────────────────────────────────────────

class TransactionType(str, Enum):
    CASH_IN  = "CASH_IN"
    CASH_OUT = "CASH_OUT"
    DEBIT    = "DEBIT"
    PAYMENT  = "PAYMENT"
    TRANSFER = "TRANSFER"


class RiskCategory(str, Enum):
    LOW    = "Low"
    MEDIUM = "Medium"
    HIGH   = "High"


class CaseStatus(str, Enum):
    OPEN          = "Open"
    UNDER_REVIEW  = "Under Review"
    ESCALATED     = "Escalated"
    RESOLVED      = "Resolved"
    FALSE_POSITIVE = "False Positive"


# ─── Transaction Schemas ───────────────────────────────────────────────────────

class TransactionInput(BaseModel):
    """Input schema for a single transaction prediction request."""
    transaction_type:      TransactionType
    amount:                float
    origin_account:        str
    destination_account:   str
    origin_balance_before: float = 0.0
    origin_balance_after:  float = 0.0
    dest_balance_before:   float = 0.0
    dest_balance_after:    float = 0.0

    @field_validator("amount")
    @classmethod
    def amount_must_be_positive(cls, v: float) -> float:
        if v <= 0:
            raise ValueError("Transaction amount must be greater than zero.")
        return round(v, 2)

    @field_validator("origin_account", "destination_account")
    @classmethod
    def account_not_empty(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Account identifier cannot be empty.")
        return v.strip()

    model_config = ConfigDict(use_enum_values=True)


class TransactionResponse(BaseModel):
    """Full transaction record (read from DB)."""
    id:                    int
    transaction_type:      str
    amount:                float
    origin_account:        str
    destination_account:   str
    origin_balance_before: Optional[float]
    origin_balance_after:  Optional[float]
    dest_balance_before:   Optional[float]
    dest_balance_after:    Optional[float]
    transaction_timestamp: datetime
    created_at:            datetime

    model_config = ConfigDict(from_attributes=True)


# ─── Prediction Schemas ────────────────────────────────────────────────────────

class FeatureImportance(BaseModel):
    """SHAP explanation for a single feature."""
    feature:    str
    value:      float
    importance: float
    direction:  str  # "increases_risk" or "decreases_risk"


class PredictionResponse(BaseModel):
    """Prediction result returned by /api/predict."""
    transaction_id:      int
    predicted_class:     int
    label:               str          # "Legitimate" or "Suspicious"
    fraud_probability:   float
    risk_category:       RiskCategory
    model_version:       str
    prediction_timestamp: datetime
    top_features:        Optional[List[FeatureImportance]] = None
    disclaimer:          str = (
        "This prediction is generated by an ML model and is not guaranteed to be "
        "correct. All flagged transactions should be reviewed by a human analyst."
    )

    model_config = ConfigDict(from_attributes=True, use_enum_values=True)


class BatchTransactionInput(BaseModel):
    """Batch prediction request schema."""
    transactions: List[TransactionInput]

    @field_validator("transactions")
    @classmethod
    def at_least_one(cls, v):
        if len(v) == 0:
            raise ValueError("Batch must contain at least one transaction.")
        if len(v) > 1000:
            raise ValueError("Batch size cannot exceed 1000 transactions.")
        return v


class BatchPredictionResponse(BaseModel):
    """Batch prediction result."""
    total:       int
    flagged:     int
    results:     List[PredictionResponse]
    batch_id:    str
    processed_at: datetime


